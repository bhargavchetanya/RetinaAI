"""Step 7 – Sample predictions for the README / report.

Runs the full inference pipeline (quality check -> CNN + TTA -> calibrated
probabilities -> referral -> Grad-CAM++ -> explanation) on a few held-out
TEST images per grade and saves:

  docs/images/sample_predictions.png   – grid: fundus | heat-map, true vs predicted
  docs/sample_results.md               – table with confidence, referral, explanation

Usage:  python scripts/07_sample_predictions.py [--per-class 2]
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import base64  # noqa: E402
import io  # noqa: E402

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

from retina.config import CLASS_NAMES, RAW_DIR, ROOT  # noqa: E402
from retina.dataset import load_split  # noqa: E402
from retina.inference import DRPredictor  # noqa: E402

OUT_IMG = ROOT / "docs" / "images" / "sample_predictions.png"
OUT_MD = ROOT / "docs" / "sample_results.md"


def b64_to_array(data_url):
    return np.array(Image.open(io.BytesIO(base64.b64decode(data_url.split(",", 1)[1]))).convert("RGB"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-class", type=int, default=2)
    args = ap.parse_args()

    test = load_split("test").sample(frac=1, random_state=7)
    picks = [(r.id_code, int(r.diagnosis)) for g in range(5)
             for r in test[test.diagnosis == g].head(args.per_class).itertuples()]

    pred = DRPredictor()
    results = []
    for id_code, true in picks:
        r = pred.predict((RAW_DIR / "train_images" / f"{id_code}.png").read_bytes())
        results.append((id_code, true, r))
        print(f"{id_code}  true={CLASS_NAMES[true]:<17} pred={r['grade_name']:<17} "
              f"conf={r['confidence']:.2f}  refer={r['refer']}")

    # ---- figure -------------------------------------------------------------
    n = len(results)
    cols = 4                                   # two samples per row (fundus + heat-map each)
    rows = int(np.ceil(n / 2))
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 3.0, rows * 3.3))
    axes = np.atleast_2d(axes)
    for ax in axes.ravel():
        ax.axis("off")
    for k, (id_code, true, r) in enumerate(results):
        row, c = divmod(k, 2)
        ok = r["grade"] == true
        axes[row, c * 2].imshow(b64_to_array(r["images"]["original"]))
        axes[row, c * 2].set_title(f"True: {CLASS_NAMES[true]}", fontsize=9)
        axes[row, c * 2 + 1].imshow(b64_to_array(r["images"]["heatmap"]))
        axes[row, c * 2 + 1].set_title(
            f"Pred: {r['grade_name']} ({r['confidence'] * 100:.0f}%)\n"
            f"{'REFER' if r['refer'] else 'no referral'}",
            fontsize=9, color="#15803d" if ok else "#b91c1c")
    fig.suptitle("RetinaAI – sample predictions on held-out test images (Grad-CAM++)", fontsize=12)
    fig.tight_layout()
    OUT_IMG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT_IMG, dpi=110)
    plt.close(fig)

    # ---- markdown table -----------------------------------------------------
    lines = ["# Sample results",
             "",
             "Predictions of the trained model on held-out **test** images (never seen in training).",
             "Generated by `scripts/07_sample_predictions.py`.",
             "",
             "![sample predictions](images/sample_predictions.png)",
             "",
             "| Image | True grade | Predicted | Confidence | P(referable) | Decision | Quality |",
             "|---|---|---|---:|---:|---|---|"]
    for id_code, true, r in results:
        mark = "✅" if r["grade"] == true else "❌"
        lines.append(f"| `{id_code}` | {CLASS_NAMES[true]} | {mark} {r['grade_name']} | "
                     f"{r['confidence'] * 100:.0f}% | {r['p_referable'] * 100:.0f}% | "
                     f"{'**Refer**' if r['refer'] else 'Routine'} | {'OK' if r['quality']['ok'] else 'Poor'} |")
    lines += ["", "## Generated explanations", ""]
    for id_code, true, r in results:
        lines.append(f"- **`{id_code}`** (true: {CLASS_NAMES[true]}) – {r['explanation']['en']}")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    acc = np.mean([r["grade"] == t for _, t, r in results])
    print(f"\n{sum(r['grade'] == t for _, t, r in results)}/{n} correct ({acc * 100:.0f}%)")
    print("saved", OUT_IMG, "and", OUT_MD)


if __name__ == "__main__":
    main()
